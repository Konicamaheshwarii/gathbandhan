// Builds one self-contained file per Edge Function in supabase/functions-paste/, for
// owners who deploy by pasting code into the Supabase dashboard editor (which takes one file).
// The Supabase CLI deploys supabase/functions/<name>/index.ts directly and does not need these.
// Run: node scripts/bundle-functions.mjs
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const fnDir = join(root, 'supabase', 'functions');
const outDir = join(root, 'supabase', 'functions-paste');
const NAMES = ['razorpay-create-order', 'razorpay-verify', 'razorpay-webhook', 'razorpay-linked-account', 'shagun-delete-account'];

const read = (p) => readFileSync(join(fnDir, p), 'utf8').replace(/\r\n/g, '\n');
/** Drops imports of the shared modules (multi-line too) and `export` keywords. */
const strip = (src) =>
  src
    .replace(/^import [^;]*?from '\.\.?\/(_shared\/)?(razorpay-core|edge)\.ts';\n/gms, '')
    .replace(/^export (?=(async |const |function |class |interface |type ))/gm, '');

const core = strip(read('_shared/razorpay-core.ts'));
const edge = strip(read('_shared/edge.ts'));
const edgeImports = edge.match(/^import .*;\n/gm) ?? [];
const edgeBody = edge.replace(/^import .*;\n/gm, '');

mkdirSync(outDir, { recursive: true });
for (const name of NAMES) {
  const fn = strip(read(`${name}/index.ts`));
  const out = [
    `// ${name}: GENERATED by scripts/bundle-functions.mjs from supabase/functions/. Do not edit;`,
    '// paste this whole file into Supabase → Edge Functions → Deploy a new function → Via Editor.',
    ...edgeImports.map((l) => l.trimEnd()),
    '',
    '// ---------- shared: razorpay-core.ts ----------',
    core.trim(),
    '',
    '// ---------- shared: edge.ts ----------',
    edgeBody.trim(),
    '',
    `// ---------- ${name}/index.ts ----------`,
    fn.trim(),
    '',
  ].join('\n');
  if (/from '\.\.?\//.test(out)) throw new Error(`${name}: a relative import was left in the bundle`);
  writeFileSync(join(outDir, `${name}.ts`), out);
  console.log(`wrote supabase/functions-paste/${name}.ts`);
}
